    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
                                        
        try {
            String sql = "INSERT INTO supplier (nama_supplier, alamat, no_telp) VALUES (?, ?, ?)";
            PreparedStatement pst = Koneksi.getConnection().prepareStatement(sql);
            pst.setString(1, txtNama.getText());
            pst.setString(2, txtAlamat.getText());
            pst.setString(3, txtTelp.getText());
            pst.executeUpdate();
            
            tampilData(); // Refresh tabel
            bersihForm(); // Kosongkan form
            javax.swing.JOptionPane.showMessageDialog(this, "Data Berhasil Disimpan!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Simpan: " + e.getMessage());
    }         // TODO add your handling code here:
        
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:                                        
        if (txtId.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data di tabel dulu!");
            return;
        }
        try {
            String sql = "UPDATE supplier SET nama_supplier=?, alamat=?, no_telp=? WHERE id_supplier=?";
            PreparedStatement pst = Koneksi.getConnection().prepareStatement(sql);
            pst.setString(1, txtNama.getText());
            pst.setString(2, txtAlamat.getText());
            pst.setString(3, txtTelp.getText());
            pst.setString(4, txtId.getText());
            pst.executeUpdate();
            
            tampilData();
            bersihForm();
            javax.swing.JOptionPane.showMessageDialog(this, "Data Berhasil Diubah!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Ubah: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void tabelSupplierMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelSupplierMouseClicked
        // TODO add your handling code here:                                           
        int baris = tabelSupplier.getSelectedRow();
        if (baris != -1) {
            txtId.setText(tabelSupplier.getValueAt(baris, 0).toString());
            txtNama.setText(tabelSupplier.getValueAt(baris, 1).toString());
            txtAlamat.setText(tabelSupplier.getValueAt(baris, 2).toString());
            txtTelp.setText(tabelSupplier.getValueAt(baris, 3).toString());
        }
    
    }//GEN-LAST:event_tabelSupplierMouseClicked

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:                                        
        if (txtId.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data di tabel dulu!");
            return;
        }
        try {
            String sql = "DELETE FROM supplier WHERE id_supplier=?";
            PreparedStatement pst = Koneksi.getConnection().prepareStatement(sql);
            pst.setString(1, txtId.getText());
            pst.executeUpdate();
            
            tampilData();
            bersihForm();
            javax.swing.JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
        }
    }//GEN-LAST:event_btnHapusActionPerformed

