    // 1. Method untuk mengisi Combo Box
    private void loadCombo() {
        try {
            // Isi Combo Kategori (Format: "ID - Nama")
            cmbKategori.removeAllItems();
            Statement st1 = Koneksi.getConnection().createStatement();
            ResultSet rs1 = st1.executeQuery("SELECT * FROM kategori");
            while (rs1.next()) {
                cmbKategori.addItem(rs1.getString("id_kategori") + " - " + rs1.getString("nama_kategori"));
            }

            // Isi Combo Supplier (Format: "ID - Nama")
            cmbSupplier.removeAllItems();
            Statement st2 = Koneksi.getConnection().createStatement();
            ResultSet rs2 = st2.executeQuery("SELECT * FROM supplier");
            while (rs2.next()) {
                cmbSupplier.addItem(rs2.getString("id_supplier") + " - " + rs2.getString("nama_supplier"));
            }
        } catch (Exception e) {
            System.out.println("Gagal Load Combo: " + e.getMessage());
        }
    }

    // 2. Method Tampil Data (Gunakan JOIN agar tampil nama kategori & supplier)
    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Kode");
        model.addColumn("Nama Barang");
        model.addColumn("Kategori");
        model.addColumn("Supplier");
        model.addColumn("Harga Beli");
        model.addColumn("Harga Jual");
        model.addColumn("Stok");
        
        try {
            String sql = "SELECT b.id_barang, b.kode_barang, b.nama_barang, k.nama_kategori, s.nama_supplier, b.harga_beli, b.harga_jual, b.stok " +
                         "FROM barang b " +
                         "JOIN kategori k ON b.id_kategori = k.id_kategori " +
                         "JOIN supplier s ON b.id_supplier = s.id_supplier";
            Statement st = Koneksi.getConnection().createStatement();
            ResultSet rs = st.executeQuery(sql);
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_barang"),
                    rs.getString("kode_barang"),
                    rs.getString("nama_barang"),
                    rs.getString("nama_kategori"),
                    rs.getString("nama_supplier"),
                    rs.getString("harga_beli"),
                    rs.getString("harga_jual"),
                    rs.getString("stok")
                });
            }
            tabelBarang.setModel(model);
        } catch (Exception e) {
            System.out.println("Gagal Tampil: " + e.getMessage());
        }
    }

