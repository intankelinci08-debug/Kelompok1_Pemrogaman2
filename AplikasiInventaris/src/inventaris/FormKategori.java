    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:                                          
        try {
            String sql = "INSERT INTO kategori (nama_kategori) VALUES (?)";
            PreparedStatement pst = Koneksi.getConnection().prepareStatement(sql);
            pst.setString(1, txtNamaKategori.getText());
            pst.executeUpdate();
            
            tampilData();
            bersihForm();
            javax.swing.JOptionPane.showMessageDialog(this, "Data Kategori Berhasil Disimpan!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Simpan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:                                         
        if (txtIdKategori.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data di tabel dulu!");
            return;
        }
        try {
            String sql = "UPDATE kategori SET nama_kategori=? WHERE id_kategori=?";
            PreparedStatement pst = Koneksi.getConnection().prepareStatement(sql);
            pst.setString(1, txtNamaKategori.getText());
            pst.setString(2, txtIdKategori.getText());
            pst.executeUpdate();
            
            tampilData();
            bersihForm();
            javax.swing.JOptionPane.showMessageDialog(this, "Data Kategori Berhasil Diubah!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Ubah: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:                                         
        if (txtIdKategori.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data di tabel dulu!");
            return;
        }
        try {
            String sql = "DELETE FROM kategori WHERE id_kategori=?";
            PreparedStatement pst = Koneksi.getConnection().prepareStatement(sql);
            pst.setString(1, txtIdKategori.getText());
            pst.executeUpdate();
            
            tampilData();
            bersihForm();
            javax.swing.JOptionPane.showMessageDialog(this, "Data Kategori Berhasil Dihapus!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
        }
    }//GEN-LAST:event_btnHapusActionPerformed

