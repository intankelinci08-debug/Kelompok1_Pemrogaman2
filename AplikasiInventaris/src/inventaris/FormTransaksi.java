    // 1. Method untuk mengisi Combo Box Barang
    private void loadCombo() {
        try {
            cmbBarang.removeAllItems();
            Statement st = Koneksi.getConnection().createStatement();
            ResultSet rs = st.executeQuery("SELECT * FROM barang");
            while (rs.next()) {
                cmbBarang.addItem(rs.getString("id_barang") + " - " + rs.getString("nama_barang"));
            }
        } catch (Exception e) {
            System.out.println("Gagal Load Combo: " + e.getMessage());
        }
    }

    // 2. Method Tampil Data (JOIN dengan tabel barang)
    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama Barang");
        model.addColumn("Jenis");
        model.addColumn("Jumlah");
        model.addColumn("Tanggal");
        model.addColumn("Keterangan");
        
        try {
            // Query JOIN untuk mengambil nama barang dari tabel barang
            String sql = "SELECT t.id_transaksi, b.nama_barang, t.jenis_transaksi, t.jumlah, t.tanggal, t.keterangan " +
                         "FROM transaksi_stok t " +
                         "JOIN barang b ON t.id_barang = b.id_barang";
            Statement st = Koneksi.getConnection().createStatement();
            ResultSet rs = st.executeQuery(sql);
            
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("id_transaksi"),
                    rs.getString("nama_barang"),
                    rs.getString("jenis_transaksi"),
                    rs.getString("jumlah"),
                    rs.getString("tanggal"),
                    rs.getString("keterangan")
                });
            }
            tabelTransaksi.setModel(model);
        } catch (Exception e) {
            System.out.println("Gagal Tampil: " + e.getMessage());
        }
    }

